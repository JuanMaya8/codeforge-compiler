import { useState } from 'react';
import {
  formatInstruction,
  formatIR,
  formatIRType,
  type ExecutionResult,
  type Instruction,
  type IRProgram,
  type SourceRunResult,
} from '../../compiler';
import { PHASE_LABELS, isCompilePhase } from '../../lib/runSummary';
import { EmptyState } from './EmptyState';
import type { LocateTarget } from './ResultsPanel';

interface IrViewProps {
  ir: IRProgram | null;
  stage: SourceRunResult['stage'];
  execution: ExecutionResult | null;
  onLocate: (target: LocateTarget) => void;
}

type Mode = 'structured' | 'text';

interface Body {
  /** Name used by the VM for this body: a function name, or null for MAIN. */
  functionName: string | null;
  title: string;
  subtitle?: string;
  instructions: Instruction[];
}

/** The real IR v2.0 program generated by the semantic/IR phase. */
export function IrView({ ir, stage, execution, onLocate }: IrViewProps) {
  const [mode, setMode] = useState<Mode>('structured');

  if (!ir) {
    const phase = isCompilePhase(stage) ? PHASE_LABELS[stage].toLowerCase() : stage;
    return (
      <EmptyState title="No se generó código intermedio">
        El IR solo se genera cuando el programa supera el análisis léxico, sintáctico y semántico. Esta vez falló el
        análisis {phase}.
      </EmptyState>
    );
  }

  const bodies: Body[] = [
    { functionName: null, title: 'MAIN', subtitle: 'código de nivel superior: la ejecución empieza aquí', instructions: ir.main },
    ...ir.functions.map((fn) => ({
      functionName: fn.name,
      title: `FUNCTION ${fn.name}(${fn.params.map((p) => `${p.name}: ${formatIRType(p.type)}`).join(', ')}): ${formatIRType(fn.returnType)}`,
      subtitle:
        fn.locals.length > 0
          ? `locales: ${fn.locals.map((local) => `${local.name}: ${formatIRType(local.type)}`).join(', ')}`
          : undefined,
      instructions: fn.body,
    })),
  ];
  const total = bodies.reduce((sum, body) => sum + body.instructions.length, 0);

  // The VM reports the PC inside the body named by `execution.functionName`.
  const executedBody = execution
    ? (ir.functions.find((fn) => fn.name === execution.functionName)?.name ?? null)
    : undefined;
  const isExecutedBody = (body: Body) => execution !== null && body.functionName === executedBody;

  return (
    <div className="data-view">
      <div className="data-view__toolbar">
        <p className="data-view__caption">
          IR versión <strong>{ir.version}</strong> · <strong>{total}</strong> instrucciones de tres direcciones en{' '}
          {bodies.length} {bodies.length === 1 ? 'cuerpo' : 'cuerpos'}. El PC es el índice de cada instrucción dentro
          de su cuerpo.
        </p>
        <div className="segmented" role="group" aria-label="Formato del IR">
          <button type="button" aria-pressed={mode === 'structured'} onClick={() => setMode('structured')}>
            Estructurado
          </button>
          <button type="button" aria-pressed={mode === 'text'} onClick={() => setMode('text')}>
            Texto
          </button>
        </div>
      </div>

      {ir.globals.length > 0 && (
        <div className="chip-list" aria-label="Variables globales">
          <span className="chip-list__label">Globales</span>
          {ir.globals.map((global) => (
            <code key={global.name} className="chip">
              {global.name}: <span className="chip__type">{formatIRType(global.type)}</span>
            </code>
          ))}
        </div>
      )}

      {execution && (
        <p className={`callout ${execution.status === 'failed' ? 'callout--runtime' : 'callout--info'}`}>
          {execution.status === 'failed'
            ? `La VM se detuvo en PC ${execution.pc} de ${execution.functionName}; la instrucción está resaltada.`
            : `La ejecución terminó en PC ${execution.pc} de ${execution.functionName} (última instrucción ejecutada, marcada).`}
        </p>
      )}

      {mode === 'text' ? (
        <pre className="code-block">{formatIR(ir, { positions: true })}</pre>
      ) : (
        bodies.map((body) => (
          <section key={body.title} className="ir-body">
            <header className="ir-body__header">
              <h3 className="ir-body__title">{body.title}</h3>
              {body.subtitle && <p className="ir-body__subtitle">{body.subtitle}</p>}
            </header>
            {body.instructions.length === 0 ? (
              <p className="data-view__caption data-view__empty">Cuerpo vacío.</p>
            ) : (
              <div className="table-scroll">
                <table className="data-table ir-table">
                  <thead>
                    <tr>
                      <th scope="col">PC</th>
                      <th scope="col">Opcode</th>
                      <th scope="col">Instrucción</th>
                      <th scope="col">Origen</th>
                    </tr>
                  </thead>
                  <tbody>
                    {body.instructions.map((instruction, pc) => {
                      const current = isExecutedBody(body) && execution?.pc === pc;
                      const failed = current && execution?.status === 'failed';
                      return (
                        <tr
                          key={pc}
                          className={[
                            instruction.op === 'LABEL' ? 'ir-table__label' : '',
                            current ? 'ir-table__current' : '',
                            failed ? 'ir-table__failed' : '',
                          ].join(' ')}
                          aria-current={current ? 'step' : undefined}
                        >
                          <td className="data-table__number">{pc}</td>
                          <td>
                            <span className={`opcode opcode--${opcodeGroup(instruction.op)}`}>{instruction.op}</span>
                          </td>
                          <td className="data-table__code">{formatInstruction(instruction)}</td>
                          <td>
                            {instruction.position ? (
                              <button
                                type="button"
                                className="link-button"
                                onClick={() =>
                                  instruction.position &&
                                  onLocate({ line: instruction.position.line, column: instruction.position.column })
                                }
                              >
                                {instruction.position.line}:{instruction.position.column}
                              </button>
                            ) : (
                              <span className="data-table__muted">—</span>
                            )}
                          </td>
                        </tr>
                      );
                    })}
                  </tbody>
                </table>
              </div>
            )}
          </section>
        ))
      )}
    </div>
  );
}

/** Visual group of an opcode, only for coloring. */
function opcodeGroup(op: Instruction['op']): string {
  if (op === 'LABEL' || op === 'JUMP' || op === 'JUMP_IF_FALSE' || op === 'JUMP_IF_TRUE') return 'flow';
  if (op === 'CALL' || op === 'PARAM' || op === 'RETURN') return 'call';
  if (op.startsWith('ARRAY_')) return 'memory';
  if (op === 'PRINT') return 'io';
  return 'data';
}
